                "\n",
                "### 1. Vấn đề toán học đối với biến liên tục\n",
                "Trong định lý Bayes cổ điển dành cho các biến ngẫu nhiên rời rạc:\n",
                "$$P(Y = k \\mid X = x) = \\frac{P(Y = k) \\cdot P(X = x \\mid Y = k)}{P(X = x)}$$\n",
                "\n",
                "Tuy nhiên, khi đặc trưng $X$ là một đại lượng ngẫu nhiên liên tục ($X \\in \\mathbb{R}$):\n",
                "- Xác suất tại một điểm đơn lẻ bất kỳ luôn bằng 0: $P(X = x) = 0$ và $P(X = x \\mid Y = k) = 0$.\n",
                "- Nếu áp dụng trực tiếp, ta gặp dạng vô định $\\frac{0}{0}$.\n",
                "\n",
                "### 2. Chứng minh chặt chẽ qua xấp xỉ tích phân trong lân cận vô cùng bé\n",
                "Để tính xác suất điều kiện khi quan sát thấy $X = x$, ta xét $X$ rơi vào một khoảng lân cận đối xứng bán kính $\\epsilon > 0$ quanh $x$:\n",
                "$$E_\\epsilon = [x - \\epsilon, x + \\epsilon]$$\n",
                "\n",
                "Theo định nghĩa của hàm mật độ xác suất (Probability Density Function - PDF) $f(u)$:\n",
                "$$P(x - \\epsilon \\le X \\le x + \\epsilon \\mid Y = k) = \\int_{x - \\epsilon}^{x + \\epsilon} f_{X \\mid Y = k}(u) \\, du$$\n",
                "\n",
                "Theo Định lý giá trị trung bình tích phân (Mean Value Theorem for Integrals), với $\\epsilon$ đủ nhỏ:\n",
                "$$\\int_{x - \\epsilon}^{x + \\epsilon} f_{X \\mid Y = k}(u) \\, du \\approx 2\\epsilon \\cdot f_{X \\mid Y = k}(x)$$\n",
                "\n",
                "Tương tự đối với xác suất toàn phần của $X$:\n",
                "$$P(x - \\epsilon \\le X \\le x + \\epsilon) = \\int_{x - \\epsilon}^{x + \\epsilon} f_X(u) \\, du \\approx 2\\epsilon \\cdot f_X(x)$$\n",
                "\n",
                "Áp dụng định lý Bayes cho biến cố $X \\in E_\\epsilon$:\n",
                "$$P(Y = k \\mid x - \\epsilon \\le X \\le x + \\epsilon) = \\frac{P(Y = k) \\cdot P(x - \\epsilon \\le X \\le x + \\epsilon \\mid Y = k)}{P(x - \\epsilon \\le X \\le x + \\epsilon)} \\approx \\frac{P(Y = k) \\cdot 2\\epsilon f_{X \\mid Y = k}(x)}{2\\epsilon f_X(x)}$$\n",
                "\n",
                "Cho $\\epsilon \\to 0$, đại lượng $2\\epsilon$ ở cả tử số và mẫu số bị triệt tiêu hoàn toàn, ta thu được **Công thức Bayes Hỗn Hợp (Hybrid Bayes Rule)**:\n",
                "$$\\mathbf{P(Y = k \\mid X = x) = \\frac{P(Y = k) \\cdot f_{X \\mid Y = k}(x)}{f_X(x)}}$$\n",
                "\n",
                "Trong đó:\n",
                "- $Y$ là biến rời rạc nhận nhãn lớp $k \\in \\{1, 2, \\dots, K\\}$.\n",
                "- $X$ là biến liên tục.\n",
                "- $f_{X \\mid Y = k}(x) = \\frac{1}{\\sqrt{2\\pi \\sigma_k^2}} \\exp\\left( -\\frac{(x - \\mu_k)^2}{2\\sigma_k^2} \\right)$ là hàm mật độ xác suất của phân phối chuẩn (Gaussian PDF).\n",
                "- Mẫu số $f_X(x) = \\sum_{j=1}^K P(Y = j) f_{X \\mid Y = j}(x)$ là hằng số đối với mọi nhãn $k$.\n",
                "\n",
                "Vì vậy trong phân loại theo quy tắc MAP (Maximum A Posteriori):\n",
                "$$\\hat{y} = \\arg\\max_k P(Y = k \\mid X = x) = \\arg\\max_k \\left[ P(Y = k) \\cdot f_{X \\mid Y = k}(x) \\right]$$\n",
                "\n",
